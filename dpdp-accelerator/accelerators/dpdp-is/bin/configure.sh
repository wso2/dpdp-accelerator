# Applies the offline configuration the accelerator needs: installs the shipped
# deployment.toml, writes the portal configuration file and applies the consent
# schema migration.
# Run this with the server STOPPED, then start it and run register-portal-app.sh.

set -e

WSO2_IS_HOME=$1
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ACCELERATOR_HOME="$(dirname "${SCRIPT_DIR}")"

if [ -z "${WSO2_IS_HOME}" ]; then
  WSO2_IS_HOME="$(dirname "${ACCELERATOR_HOME}")"
fi

if [ ! -d "${WSO2_IS_HOME}/repository/components" ]; then
  printf '\nERROR: %s is not a valid Carbon product path.\n\n' "${WSO2_IS_HOME}"
  exit 2
fi

# This script replaces deployment.toml and runs a schema migration against the
# embedded database, neither of which is safe while the server holds it open.
if pgrep -f "carbon.home=${WSO2_IS_HOME}" > /dev/null 2>&1; then
  printf '\nERROR: the Identity Server at %s is still running.\n' "${WSO2_IS_HOME}"
  printf '       Stop it first: sh %s/bin/wso2server.sh stop\n\n' "${WSO2_IS_HOME}"
  exit 2
fi

# shellcheck source=/dev/null
source "${ACCELERATOR_HOME}/repository/conf/configure.properties"

DEPLOYMENT_TOML="${WSO2_IS_HOME}/repository/conf/deployment.toml"
TOML_TEMPLATE="${ACCELERATOR_HOME}/${PRODUCT_CONF_PATH}"
TOML_STAGING="${ACCELERATOR_HOME}/repository/resources/deployment.toml"
PORTAL_PROPERTIES="${WSO2_IS_HOME}/repository/conf/dpdp-portal.properties"

echo "Product home: ${WSO2_IS_HOME}"
echo

# ---------------------------------------------------------------- deployment.toml
# The accelerator ships a complete deployment.toml and installs it wholesale.
# Appending to whatever the product already had could not work: a second
# [consent_mgt] table makes the file unparseable, and the result depended on the
# state the operator's file happened to be in.
if [ ! -f "${TOML_TEMPLATE}" ]; then
  echo "ERROR: no deployment.toml template at ${TOML_TEMPLATE}"
  echo "       Check PRODUCT_CONF_PATH in repository/conf/configure.properties."
  exit 2
fi

echo "[1/3] Installing deployment.toml from $(basename "${TOML_TEMPLATE}")"
cp "${TOML_TEMPLATE}" "${TOML_STAGING}"

# Substituted on the staging copy so the shipped template keeps its placeholders.
# None of these tokens is a prefix of another, so the order does not matter.
for pair in "IS_HOSTNAME=${IS_HOSTNAME}" \
            "IS_ADMIN_USERNAME=${IS_ADMIN_USERNAME}" \
            "IS_ADMIN_PASSWORD=${IS_ADMIN_PASSWORD}"; do
  token="${pair%%=*}"
  value="${pair#*=}"
  # sed -i needs a backup suffix to be portable across GNU and BSD; remove it after.
  sed -i.tmp "s|${token}|${value}|g" "${TOML_STAGING}"
  rm -f "${TOML_STAGING}.tmp"
done

if [ -f "${DEPLOYMENT_TOML}" ]; then
  BACKUP="${DEPLOYMENT_TOML}.bak-$(date +%Y%m%d%H%M%S)"
  cp "${DEPLOYMENT_TOML}" "${BACKUP}"
  echo "      Previous deployment.toml backed up to $(basename "${BACKUP}")"
fi

cp "${TOML_STAGING}" "${DEPLOYMENT_TOML}"
rm -f "${TOML_STAGING}"
echo "      deployment.toml was REPLACED, not merged - re-apply any local"
echo "      customisation from the backup before starting the server."

# ------------------------------------------------------------- portal properties
echo "[2/3] Writing ${PORTAL_PROPERTIES}"
IS_BASE_URL="https://${IS_HOSTNAME}:${IS_PORT}"
if [ -f "${PORTAL_PROPERTIES}" ] && grep -q "^oauth.client.id=.\+" "${PORTAL_PROPERTIES}"; then
  echo "      Existing client credentials found; only the base URLs are refreshed."
  CLIENT_ID=$(grep "^oauth.client.id=" "${PORTAL_PROPERTIES}" | cut -d= -f2-)
  CLIENT_SECRET=$(grep "^oauth.client.secret=" "${PORTAL_PROPERTIES}" | cut -d= -f2-)
else
  CLIENT_ID=""
  CLIENT_SECRET=""
fi

cat > "${PORTAL_PROPERTIES}" <<EOF
# WSO2 DPDP Accelerator - Consent Portal configuration.
# Generated by configure.sh; client credentials are filled in by
# register-portal-app.sh. This file survives an accelerator upgrade.
identity.server.base.url=${IS_BASE_URL}
identity.server.internal.base.url=https://localhost:${IS_PORT}
oauth.client.id=${CLIENT_ID}
oauth.client.secret=${CLIENT_SECRET}
cookie.secure=true
EOF

# ------------------------------------------------------------ consent DB migration
if [ "${APPLY_CONSENT_DB_MIGRATION}" != "true" ]; then
  echo "[3/3] Skipping the consent schema migration (APPLY_CONSENT_DB_MIGRATION is not true)."
else
  MIGRATION="${WSO2_IS_HOME}/dbscripts/migrations/consent/${DB_TYPE}-migration.txt"
  if [ ! -f "${MIGRATION}" ]; then
    echo "[3/3] WARNING: no migration script at ${MIGRATION}; skipping."
  elif [ "${DB_TYPE}" != "h2" ]; then
    # Only the bundled H2 database can be migrated without external credentials.
    echo "[3/3] Apply ${MIGRATION} to your ${DB_TYPE} identity database before starting the server."
  else
    H2_JAR=$(find "${WSO2_IS_HOME}/repository/components/plugins" -name "h2-engine_*.jar" | head -1)
    if [ -z "${H2_JAR}" ]; then
      echo "[3/3] WARNING: could not locate the H2 engine jar; apply ${MIGRATION} manually."
    else
      echo "[3/3] Applying the consent schema migration to the embedded H2 database"
      TMP_SQL="$(mktemp)"
      grep -v '^#' "${MIGRATION}" > "${TMP_SQL}"
      java -cp "${H2_JAR}" org.h2.tools.RunScript \
        -url "jdbc:h2:${WSO2_IS_HOME}/repository/database/WSO2IDENTITY_DB" \
        -user wso2carbon -password wso2carbon -script "${TMP_SQL}"
      rm -f "${TMP_SQL}"
      echo "      Migration applied."
    fi
  fi
fi

echo
echo "Configuration complete. Now:"
echo "  1. Start the Identity Server."
echo "  2. Run: sh bin/register-portal-app.sh ${WSO2_IS_HOME}"
